import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "csv-parse/sync";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const season = Number(process.argv[2] || 2025);
const sourceUrl = `https://github.com/nflverse/nflverse-data/releases/download/stats_player/stats_player_reg_${season}.csv`;
const response = await fetch(sourceUrl);
if (!response.ok) throw new Error(`Unable to download ${sourceUrl}: HTTP ${response.status}`);
const rows = parse(await response.text(), { columns: true, skip_empty_lines: true })
  .filter((row) => ["QB", "RB", "WR", "TE"].includes(row.position) && Number(row.games) > 0)
  .sort((a, b) => a.player_id.localeCompare(b.player_id));

const number = (value) => Number(value || 0);
const records = rows.map((row) => `  ${JSON.stringify(row.player_id)}: nfl(${JSON.stringify(row.player_display_name)}, ${JSON.stringify(row.position)}, ${number(row.games)}, ${number(row.passing_yards)}, ${number(row.passing_tds)}, ${number(row.rushing_yards)}, ${number(row.rushing_tds)}, ${number(row.receptions)}, ${number(row.receiving_yards)}, ${number(row.receiving_tds)}),`).join("\n");
const output = `// Generated by scripts/generate-prior-season-player-stats.mjs from ${sourceUrl}.
// 2023+ player stats require attribution to FTN Data via nflverse (CC-BY-SA 4.0).
export type PriorSeasonPlayerStats = {
  playerName: string;
  position: "QB" | "RB" | "WR" | "TE";
  gamesPlayed: number;
  passingYards: number;
  passingTouchdowns: number;
  rushingYards: number;
  rushingTouchdowns: number;
  receptions: number;
  receivingYards: number;
  receivingTouchdowns: number;
  season: ${season};
  league: "NFL";
  sourceUrl: string;
};

const NFL_SOURCE = "https://github.com/nflverse/nflverse-data/releases/tag/stats_player";
const nfl = (playerName: string, position: PriorSeasonPlayerStats["position"], gamesPlayed: number, passingYards: number, passingTouchdowns: number, rushingYards: number, rushingTouchdowns: number, receptions: number, receivingYards: number, receivingTouchdowns: number): PriorSeasonPlayerStats => ({ playerName, position, gamesPlayed, passingYards, passingTouchdowns, rushingYards, rushingTouchdowns, receptions, receivingYards, receivingTouchdowns, season: ${season}, league: "NFL", sourceUrl: NFL_SOURCE });

export const PRIOR_SEASON_PLAYER_STATS: Record<string, PriorSeasonPlayerStats> = {
${records}
};

export function priorSeasonPlayerStats(playerId: string): PriorSeasonPlayerStats | null {
  return PRIOR_SEASON_PLAYER_STATS[playerId] || null;
}

export function projectEighteenGamePace(total: number, gamesPlayed: number): number {
  if (!Number.isFinite(total) || !Number.isFinite(gamesPlayed) || gamesPlayed <= 0) return 0;
  return Number(((total / gamesPlayed) * 18).toFixed(1));
}
`;

await writeFile(path.join(root, "src/prior-season-player-stats.ts"), output);
console.log(`Generated ${rows.length} ${season} NFL player records.`);
